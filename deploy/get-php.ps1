# Downloads the latest PHP 8.3.x (NTS, x64) for Windows from windows.php.net
# and prepares a portable runtime in deploy\php with a ready php.ini.
#
# Usage (from anywhere):  powershell -ExecutionPolicy Bypass -File deploy\get-php.ps1
#
# windows.php.net/downloads/releases/ only keeps the latest patch of each
# branch, so the exact filename is discovered from the directory listing.

[CmdletBinding()]
param(
    [string]$Branch = '8.3'
)

$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12

$BaseUrl   = 'https://windows.php.net/downloads/releases/'
$DeployDir = $PSScriptRoot
$PhpDir    = Join-Path $DeployDir 'php'

Write-Host "==> Reading $BaseUrl"
$listing = (Invoke-WebRequest -Uri $BaseUrl -UseBasicParsing).Content

# e.g. php-8.3.36-nts-Win32-vs16-x64.zip or a rebuild like php-8.3.36-1-nts-Win32-vs16-x64.zip
$pattern = 'php-' + [regex]::Escape($Branch) + '\.(\d+)(?:-(\d+))?-nts-Win32-vs\d+-x64\.zip(?![.\w])'
$found = [regex]::Matches($listing, $pattern) |
    ForEach-Object {
        $build = 0
        if ($_.Groups[2].Success) { $build = [int]$_.Groups[2].Value }
        [pscustomobject]@{ Name = $_.Value; Patch = [int]$_.Groups[1].Value; Build = $build }
    } |
    Sort-Object Name -Unique |
    Sort-Object Patch, Build -Descending

if (-not $found) {
    throw "No PHP $Branch NTS x64 zip found in the listing at $BaseUrl"
}

$zipName = @($found)[0].Name
$zipPath = Join-Path $DeployDir $zipName
Write-Host "==> Latest build: $zipName"

if (-not (Test-Path $zipPath)) {
    Write-Host "==> Downloading $BaseUrl$zipName"
    Invoke-WebRequest -Uri ($BaseUrl + $zipName) -OutFile $zipPath -UseBasicParsing
} else {
    Write-Host "==> Using already downloaded $zipPath"
}

# Verify it is a zip (PK header) ...
$stream = [IO.File]::OpenRead($zipPath)
try {
    $header = New-Object byte[] 2
    [void]$stream.Read($header, 0, 2)
} finally {
    $stream.Close()
}
if ($header[0] -ne 0x50 -or $header[1] -ne 0x4B) {
    Remove-Item $zipPath -Force
    throw "$zipName is not a zip file (download corrupted?)"
}

# ... and its SHA-256 against the checksum list published in the same directory.
$sums = (Invoke-WebRequest -Uri ($BaseUrl + 'sha256sum.txt') -UseBasicParsing).Content
$sumLine = ($sums -split "`n") | Where-Object { $_ -match [regex]::Escape($zipName) } | Select-Object -First 1
if ($sumLine) {
    $expected = ($sumLine.Trim() -split '\s+')[0].ToLower()
    $actual = (Get-FileHash -Algorithm SHA256 $zipPath).Hash.ToLower()
    if ($expected -ne $actual) {
        Remove-Item $zipPath -Force
        throw "SHA-256 mismatch for $zipName (expected $expected, got $actual)"
    }
    Write-Host "==> SHA-256 verified"
} else {
    Write-Warning "No checksum listed for $zipName; skipped SHA-256 check"
}

Write-Host "==> Extracting to $PhpDir"
if (Test-Path $PhpDir) { Remove-Item $PhpDir -Recurse -Force }
Add-Type -AssemblyName System.IO.Compression.FileSystem
[IO.Compression.ZipFile]::ExtractToDirectory($zipPath, $PhpDir)

# php.ini based on php.ini-production, with exactly the extensions the app needs.
$ini = Get-Content (Join-Path $PhpDir 'php.ini-production') -Raw
$ini += @"

; ---------------------------------------------------------------------------
; CafePOS POS (generated by deploy\get-php.ps1)
; ---------------------------------------------------------------------------
extension_dir = "ext"
extension=pdo_sqlite
extension=sqlite3
extension=mbstring
extension=fileinfo
extension=openssl
extension=curl
extension=zip
extension=intl

zend_extension=opcache
opcache.enable=1
opcache.enable_cli=0
opcache.memory_consumption=128
opcache.max_accelerated_files=20000
opcache.validate_timestamps=1

memory_limit=256M
"@
Set-Content -Path (Join-Path $PhpDir 'php.ini') -Value $ini -Encoding Ascii

# PHP needs the Visual C++ 2015-2022 runtime. A fresh Windows install may not have it,
# so ship the DLLs app-locally next to php.exe (copied from this build machine).
foreach ($dll in 'vcruntime140.dll', 'vcruntime140_1.dll', 'msvcp140.dll') {
    $src = Join-Path $env:WINDIR "System32\$dll"
    if ((Test-Path $src) -and -not (Test-Path (Join-Path $PhpDir $dll))) {
        Copy-Item $src $PhpDir
        Write-Host "==> Bundled $dll"
    }
}

$sizeMb = [math]::Round((Get-Item $zipPath).Length / 1MB, 1)
Write-Host ""
Write-Host "Done: $zipName ($sizeMb MB) -> $PhpDir"
& (Join-Path $PhpDir 'php.exe') -v
